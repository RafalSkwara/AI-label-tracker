// Turns the supplies seed JSON into one insert-only SQL file (run once via execute_sql; re-running inserts nothing).
// Usage: node scripts/gen-supplies-seed.mjs [seed.json]
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";

const src = process.argv[2] ?? "context/changes/household-supplies/inputs/zapasy-seed.json";
const out = "supabase/seed/supplies_seed.sql";
const { items } = JSON.parse(readFileSync(src, "utf8"));

const TABS = {
  A: { name: "A: niezbędne", description: "niezbędne, niedrogie", sort: 1 },
  B: { name: "B: droższe", description: "droższe, bardzo przydatne", sort: 2 },
};
const q = (v) => (v == null ? "null" : typeof v === "string" ? `'${v.replaceAll("'", "''")}'` : String(v));

const lines = ["-- Generated by scripts/gen-supplies-seed.mjs; do not edit. Insert-only and idempotent.", "begin;", ""];
for (const [tier, t] of Object.entries(TABS)) {
  const keys = items.filter((i) => i.tier === tier).map((i) => q(i.key)).join(", ");
  lines.push(
    "insert into public.supply_tabs (name, description, sort_order)",
    `select ${q(t.name)}, ${q(t.description)}, ${t.sort}`,
    `where not exists (select 1 from public.supply_tabs where name = ${q(t.name)})`,
    `  and not exists (select 1 from public.supply_items where key in (${keys}));`,
    "",
  );
}
lines.push(
  "insert into public.supply_items (key, tab_id, category, name, quantity, details, price_min, price_max, price_label, own_price, checked, removed, sort_order)",
  "select v.key, (select id from public.supply_tabs where name = v.tab and not archived order by created_at limit 1),",
  "  v.category, v.name, v.quantity, null, v.price_min, v.price_max, v.price_label, v.own_price, v.checked, v.removed, v.sort_order",
  "from (values",
);
lines.push(
  items
    .map((i) => `  (${q(i.key)}, ${q(TABS[i.tier].name)}, ${q(i.category)}, ${q(i.name)}, ${q(i.quantity)}, ${q(i.price_min)}::numeric, ${q(i.price_max)}::numeric, ${q(i.price_label)}, ${q(i.own_price)}::numeric, ${i.checked}, ${i.removed}, ${i.sort_order})`)
    .join(",\n"),
  ") as v (key, tab, category, name, quantity, price_min, price_max, price_label, own_price, checked, removed, sort_order)",
  "where exists (select 1 from public.supply_tabs where name = v.tab and not archived)",
  "on conflict (key) do nothing;",
  "",
  "commit;",
  "",
  "select (select count(*) from public.supply_tabs) as tabs,",
  "  (select count(*) from public.supply_items where not removed) as active,",
  "  (select count(*) from public.supply_items where removed) as removed;",
  "",
);
mkdirSync("supabase/seed", { recursive: true });
writeFileSync(out, lines.join("\n"));
console.log(`${out}: ${items.length} items`);
